-- YEMEK TADINDA personnel registry and monthly attendance module.
-- Tables are private. Browser access is restricted to admin-checked SECURITY DEFINER RPCs.
create table if not exists public.personnel (
 id bigint generated by default as identity primary key,
 full_name text not null check (char_length(btrim(full_name)) between 2 and 150),
 start_date date not null,
 job_title text not null check (char_length(btrim(job_title)) between 2 and 120),
 national_id_cipher text not null,
 national_id_hash text not null unique,
 phone text not null default '',
 is_active boolean not null default true,
 created_by uuid,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.personnel_months (
 id bigint generated by default as identity primary key,
 personnel_id bigint not null references public.personnel(id) on delete restrict,
 month_date date not null check (month_date=date_trunc('month',month_date)::date),
 signatory_name text not null default '',
 updated_at timestamptz not null default now(),
 unique(personnel_id,month_date)
);
create table if not exists public.personnel_attendance (
 id bigint generated by default as identity primary key,
 personnel_id bigint not null references public.personnel(id) on delete restrict,
 attendance_date date not null,
 day_code text not null check (day_code in ('X','I','Y')),
 updated_at timestamptz not null default now(),
 unique(personnel_id,attendance_date)
);
create index if not exists personnel_active_name_idx on public.personnel(is_active,full_name);
create index if not exists personnel_attendance_person_date_idx on public.personnel_attendance(personnel_id,attendance_date);

alter table public.personnel enable row level security;
alter table public.personnel_months enable row level security;
alter table public.personnel_attendance enable row level security;
drop policy if exists "Personnel admins only" on public.personnel;
create policy "Personnel admins only" on public.personnel for all to authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists "Personnel months admins only" on public.personnel_months;
create policy "Personnel months admins only" on public.personnel_months for all to authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists "Personnel attendance admins only" on public.personnel_attendance;
create policy "Personnel attendance admins only" on public.personnel_attendance for all to authenticated using(public.is_admin()) with check(public.is_admin());
revoke all on public.personnel,public.personnel_months,public.personnel_attendance from anon,authenticated;
grant all on public.personnel,public.personnel_months,public.personnel_attendance to service_role;

