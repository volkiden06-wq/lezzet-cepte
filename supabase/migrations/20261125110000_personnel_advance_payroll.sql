create or replace function public.admin_get_personnel_payroll_month(p_personnel_id bigint, p_month date)
returns jsonb language plpgsql security definer set search_path = ''
as $function$
declare v_result jsonb;
begin
  if not coalesce(public.is_admin(), false) then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  if p_month is null or p_month <> date_trunc('month', p_month)::date then
    raise exception 'Ay tarihi ayın ilk günü olmalıdır.';
  end if;
  if not exists(select 1 from public.personnel where id = p_personnel_id) then
    raise exception 'Personel kaydı bulunamadı.';
  end if;
  select jsonb_build_object(
    'personnel_id', p_personnel_id, 'month_date', p_month,
    'monthly_salary', coalesce(pm.monthly_salary, 0),
    'salary_saved', (pm.id is not null), 'note', coalesce(pm.note, ''),
    'advances', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', a.id, 'advance_date', a.advance_date, 'amount', a.amount,
        'description', a.description, 'created_at', a.created_at,
        'voided_at', a.voided_at, 'void_reason', a.void_reason
      ) order by a.advance_date, a.id)
      from public.personnel_advances a
      where a.personnel_id = p_personnel_id
        and a.advance_date >= p_month
        and a.advance_date < (p_month + interval '1 month')
    ), '[]'::jsonb)
  ) into v_result
  from (select 1) seed
  left join public.personnel_payroll_months pm
    on pm.personnel_id = p_personnel_id and pm.month_date = p_month;
  return coalesce(v_result, '{}'::jsonb);
end;
$function$;

create or replace function public.admin_save_personnel_payroll_month(
  p_personnel_id bigint, p_month date, p_monthly_salary numeric, p_note text default ''
) returns jsonb language plpgsql security definer set search_path = ''
as $function$
declare v_saved public.personnel_payroll_months%rowtype;
begin
  if not coalesce(public.is_admin(), false) then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  if p_month is null or p_month <> date_trunc('month', p_month)::date then
    raise exception 'Ay tarihi ayın ilk günü olmalıdır.';
  end if;
  if p_monthly_salary is null or p_monthly_salary < 0 or p_monthly_salary > 9999999999.99 then
    raise exception 'Geçerli bir aylık maaş girin.';
  end if;
  if char_length(coalesce(p_note, '')) > 1000 then
    raise exception 'Açıklama en fazla 1000 karakter olabilir.';
  end if;
  if not exists(select 1 from public.personnel where id = p_personnel_id) then
    raise exception 'Personel kaydı bulunamadı.';
  end if;
  insert into public.personnel_payroll_months(personnel_id, month_date, monthly_salary, note, updated_at)
  values(p_personnel_id, p_month, round(p_monthly_salary, 2), btrim(coalesce(p_note, '')), now())
  on conflict(personnel_id, month_date) do update
    set monthly_salary = excluded.monthly_salary, note = excluded.note, updated_at = now()
  returning * into v_saved;
  return jsonb_build_object('success', true, 'monthly_salary', v_saved.monthly_salary,
    'note', v_saved.note, 'updated_at', v_saved.updated_at);
end;
$function$;

