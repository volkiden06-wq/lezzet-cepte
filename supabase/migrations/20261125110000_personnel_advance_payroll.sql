create or replace function public.admin_void_personnel_advance(
  p_advance_id bigint, p_reason text default 'Yönetici tarafından iptal edildi'
) returns boolean language plpgsql security definer set search_path = ''
as $function$
begin
  if not coalesce(public.is_admin(), false) then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  if char_length(coalesce(p_reason, '')) > 300 then
    raise exception 'İptal açıklaması en fazla 300 karakter olabilir.';
  end if;
