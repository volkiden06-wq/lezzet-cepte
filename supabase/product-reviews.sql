-- YEMEK TADINDA - Verified customer product reviews
-- Re-runnable setup. This feature uses a separate table and does not alter commerce data.

create table if not exists public.product_reviews (
  id bigint generated by default as identity primary key,
  order_number text not null,
  product_id text not null,
  product_name text not null,
  display_name text not null,
  rating smallint not null check (rating between 1 and 5),
  comment text,
  is_approved boolean not null default false,
  moderation_status text not null default 'pending',
  created_at timestamptz not null default now(),
  moderated_at timestamptz,
  constraint product_reviews_comment_length check (comment is null or char_length(comment) <= 500),
  constraint product_reviews_order_product_unique unique (order_number, product_id),
  constraint product_reviews_moderation_status_check check (moderation_status in ('pending','approved','rejected')),
  constraint product_reviews_approval_consistency_check check ((moderation_status = 'approved') = is_approved)
);

alter table public.product_reviews add column if not exists moderation_status text not null default 'pending';
alter table public.product_reviews drop constraint if exists product_reviews_moderation_status_check;
alter table public.product_reviews add constraint product_reviews_moderation_status_check
  check (moderation_status in ('pending','approved','rejected'));
alter table public.product_reviews drop constraint if exists product_reviews_approval_consistency_check;
alter table public.product_reviews add constraint product_reviews_approval_consistency_check
  check ((moderation_status = 'approved') = is_approved);

update public.product_reviews
   set moderation_status = case when is_approved then 'approved' else 'pending' end
 where (moderation_status = 'approved') is distinct from is_approved;

create index if not exists product_reviews_approved_product_created_idx
  on public.product_reviews (product_id, created_at desc)
  where is_approved = true;
create index if not exists product_reviews_moderation_created_idx
  on public.product_reviews (moderation_status, created_at desc);

alter table public.product_reviews enable row level security;
revoke all on table public.product_reviews from anon, authenticated;
grant select on table public.product_reviews to anon, authenticated;
grant update (is_approved, moderated_at, moderation_status) on table public.product_reviews to authenticated;
revoke all on sequence public.product_reviews_id_seq from anon, authenticated;

drop policy if exists "Approved product reviews are public" on public.product_reviews;
create policy "Approved product reviews are public"
  on public.product_reviews for select to anon, authenticated
  using (is_approved = true);

drop policy if exists "Admins can read all product reviews" on public.product_reviews;
create policy "Admins can read all product reviews"
  on public.product_reviews for select to authenticated
  using ((select public.is_admin()));

drop policy if exists "Admins can moderate product reviews" on public.product_reviews;
create policy "Admins can moderate product reviews"
  on public.product_reviews for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create or replace function public.submit_product_review(
  p_order_number text,
  p_phone text,
  p_product_id text,
  p_rating integer,
  p_comment text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_order_number text := pg_catalog.upper(pg_catalog.btrim(coalesce(p_order_number, '')));
  v_phone text := pg_catalog.regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
  v_product_id text := pg_catalog.btrim(coalesce(p_product_id, ''));
  v_customer_name text;
  v_display_name text;
  v_items jsonb;
  v_product_name text;
  v_comment text := nullif(pg_catalog.left(pg_catalog.btrim(coalesce(p_comment, '')), 500), '');
  v_review_id bigint;
begin
  if pg_catalog.length(v_order_number) not between 5 and 64 then
    raise exception 'Sipariş numarası geçersiz.';
  end if;
  if pg_catalog.length(v_phone) not between 10 and 15 then
    raise exception 'Geçerli telefon numarası girin.';
  end if;
  if pg_catalog.length(v_product_id) not between 1 and 100 then
    raise exception 'Ürün bilgisi geçersiz.';
  end if;
  if p_rating is null or p_rating not between 1 and 5 then
    raise exception 'Puan 1 ile 5 yıldız arasında olmalıdır.';
  end if;

  select o.customer_name, o.items
    into v_customer_name, v_items
    from public.orders o
   where pg_catalog.upper(pg_catalog.btrim(coalesce(o.order_number, ''))) = v_order_number
     and pg_catalog.regexp_replace(coalesce(o.customer_phone, ''), '[^0-9]', '', 'g') = v_phone
     and o.status = 'Teslim edildi'
   limit 1;

  if not found then
    select a.customer_name, a.items
      into v_customer_name, v_items
      from public.order_history_archive a
     where pg_catalog.upper(pg_catalog.btrim(coalesce(a.order_number, ''))) = v_order_number
       and pg_catalog.regexp_replace(coalesce(a.customer_phone, ''), '[^0-9]', '', 'g') = v_phone
       and a.status = 'Teslim edildi'
     limit 1;
  end if;

  if not found or v_items is null or pg_catalog.jsonb_typeof(v_items) <> 'array' then
    raise exception 'Yalnızca telefonunuzla eşleşen teslim edilmiş siparişleri değerlendirebilirsiniz.';
  end if;

  select coalesce(
    pg_catalog.max(
      case when e.item->>'id' = v_product_id
        then coalesce(nullif(e.item->>'base_product_name', ''), nullif(e.item->>'name', ''))
      end
    ),
    pg_catalog.max(
      case when e.item->>'free_gift_product_id' = v_product_id
        then nullif(e.item->>'free_gift_name', '')
      end
    )
  )
    into v_product_name
    from pg_catalog.jsonb_array_elements(v_items) as e(item)
   where e.item->>'id' = v_product_id
      or e.item->>'free_gift_product_id' = v_product_id;

  if v_product_name is null then
    raise exception 'Bu ürün, doğrulanan siparişinizde bulunamadı.';
  end if;

  v_display_name := coalesce(
    nullif(pg_catalog.split_part(pg_catalog.btrim(coalesce(v_customer_name, '')), ' ', 1), ''),
    'Müşteri'
  );
  if pg_catalog.split_part(pg_catalog.btrim(coalesce(v_customer_name, '')), ' ', 2) <> '' then
    v_display_name := v_display_name || ' ' ||
      pg_catalog.left(pg_catalog.split_part(pg_catalog.btrim(v_customer_name), ' ', 2), 1) || '.';
  end if;

  insert into public.product_reviews (
    order_number, product_id, product_name, display_name, rating, comment
  )
  values (
    v_order_number, v_product_id, v_product_name, v_display_name, p_rating::smallint, v_comment
  )
  on conflict (order_number, product_id) do nothing
  returning id into v_review_id;

  if v_review_id is null then
    raise exception 'Bu sipariş ve ürün için daha önce değerlendirme gönderdiniz.';
  end if;

  return pg_catalog.jsonb_build_object(
    'review_id', v_review_id,
    'product_id', v_product_id,
    'product_name', v_product_name,
    'status', 'pending',
    'message', 'Değerlendirmeniz alındı. Yayınlanmadan önce yönetici kontrolünden geçecek.'
  );
end;
$function$;

revoke all on function public.submit_product_review(text, text, text, integer, text) from public;
grant execute on function public.submit_product_review(text, text, text, integer, text) to anon, authenticated;
