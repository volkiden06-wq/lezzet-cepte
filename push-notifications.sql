-- YEMEK TADINDA Web Push bildirim altyapısı
-- Mevcut ürün, kategori ve sipariş tablolarına dokunmaz.
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique,
  subscription jsonb not null,
  user_agent text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.push_subscriptions enable row level security;
revoke all on public.push_subscriptions from anon, authenticated;
grant usage on schema public to anon, authenticated;

create or replace function public.save_push_subscription(
  p_endpoint text,
  p_subscription jsonb,
  p_user_agent text default ''
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_endpoint is null or length(p_endpoint) < 30
     or p_subscription is null
     or p_subscription->>'endpoint' is null
     or p_subscription->'keys'->>'p256dh' is null
     or p_subscription->'keys'->>'auth' is null then
    raise exception 'Geçersiz bildirim aboneliği';
  end if;
  insert into public.push_subscriptions(endpoint, subscription, user_agent, updated_at)
  values (p_endpoint, p_subscription, coalesce(p_user_agent,''), now())
  on conflict (endpoint) do update
    set subscription=excluded.subscription,
        user_agent=excluded.user_agent,
        updated_at=now();
end;
$$;
revoke all on function public.save_push_subscription(text,jsonb,text) from public;
grant execute on function public.save_push_subscription(text,jsonb,text) to anon, authenticated;
notify pgrst, 'reload schema';

