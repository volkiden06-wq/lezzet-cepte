create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 customer_name text not null,
 phone text not null,
 order_type text not null default 'Adrese teslim',
 payment_method text not null default 'Kapıda Nakit' check (payment_method in ('Kapıda Nakit','Kapıda Kredi Kartı')),
 note text not null default '',
 items jsonb not null,
 total numeric(12,2) not null check (total >= 0),
 status text not null default 'Yeni' check (status in ('Yeni','Hazırlanıyor','Yola çıktı','Teslim edildi','İptal')),
 created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
-- Do not create public read/write policies. All access in this starter is through Netlify Functions using server-only service-role key.
