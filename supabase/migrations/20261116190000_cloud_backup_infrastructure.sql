-- YEMEK TADINDA cloud backup infrastructure
-- Secrets are generated and stored in Supabase Vault, never committed to Git.

create extension if not exists pg_cron;

create table if not exists public.site_backup_runs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  status text not null check (status in ('success','failed')),
  archive_path text,
  database_path text,
  table_count integer not null default 0,
  row_count integer not null default 0,
  storage_file_count integer not null default 0,
  archive_bytes bigint not null default 0,
  error_message text
);

alter table public.site_backup_runs enable row level security;

drop policy if exists "Site backup admins can view runs" on public.site_backup_runs;
create policy "Site backup admins can view runs"
on public.site_backup_runs for select to authenticated
using (public.is_admin());

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'yemektadinda-backups',
  'yemektadinda-backups',
  false,
  52428800,
  array['application/gzip','application/json','application/octet-stream','image/jpeg','image/png','image/webp']::text[]
)
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "YemekTadinda backup admin read" on storage.objects;
create policy "YemekTadinda backup admin read"
on storage.objects for select to authenticated
using (bucket_id = 'yemektadinda-backups' and public.is_admin());

drop policy if exists "YemekTadinda backup admin delete" on storage.objects;
create policy "YemekTadinda backup admin delete"
on storage.objects for delete to authenticated
using (bucket_id = 'yemektadinda-backups' and public.is_admin());

alter table public.site_backup_runs
add column if not exists database_path text;

do $$
begin
  if not exists (select 1 from vault.secrets where name = 'yemektadinda_backup_token') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'yemektadinda_backup_token',
      'Private shared token for the scheduled YEMEK TADINDA cloud backup Edge Function'
    );
  end if;
  if not exists (select 1 from vault.secrets where name = 'yemektadinda_project_url') then
    perform vault.create_secret(
      'https://jlpqdjhxdpmighnpebkj.supabase.co',
      'yemektadinda_project_url',
      'YEMEK TADINDA scheduled cloud backup API URL'
    );
  end if;
  if not exists (select 1 from vault.secrets where name = 'yemektadinda_publishable_key') then
    raise notice 'Set yemektadinda_publishable_key in Vault before enabling cron.';
  end if;
end
$$;

create or replace function public.verify_yemektadinda_backup_token(p_token text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  expected_token text;
begin
  select decrypted_secret into expected_token
  from vault.decrypted_secrets
  where name = 'yemektadinda_backup_token'
  limit 1;

  return expected_token is not null
    and p_token is not null
    and length(p_token) >= 32
    and p_token = expected_token;
end;
$$;

revoke all on function public.verify_yemektadinda_backup_token(text) from public, anon, authenticated;
grant execute on function public.verify_yemektadinda_backup_token(text) to service_role;
grant select on public.site_backup_runs to authenticated;

-- Schedules a daily archive at 02:15 Europe/Istanbul (23:15 UTC).
select cron.schedule(
  'yemektadinda-daily-cloud-backup',
  '15 23 * * *',
  $job$
    select net.http_post(
      url := (select decrypted_secret from vault.decrypted_secrets where name='yemektadinda_project_url')
        || '/functions/v1/cloud-backup',
      headers := jsonb_build_object(
        'Content-Type','application/json',
        'apikey',(select decrypted_secret from vault.decrypted_secrets where name='yemektadinda_publishable_key'),
        'Authorization','Bearer ' || (select decrypted_secret from vault.decrypted_secrets where name='yemektadinda_publishable_key'),
        'x-backup-token',(select decrypted_secret from vault.decrypted_secrets where name='yemektadinda_backup_token')
      ),
      body := jsonb_build_object('source','daily-cron'),
      timeout_milliseconds := 120000
    );
  $job$
);
