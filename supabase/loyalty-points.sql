-- YEMEK TADINDA: additive loyalty points.
-- New tables only; existing orders, catalog, campaigns and push records remain untouched.
create table if not exists public.loyalty_accounts (
  phone_digits text primary key,
  customer_name text not null default '',
  points_balance integer not null default 0 check (points_balance >= 0),
  lifetime_earned integer not null default 0 check (lifetime_earned >= 0),
  lifetime_redeemed integer not null default 0 check (lifetime_redeemed >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint loyalty_accounts_phone_digits_length check (length(phone_digits) between 10 and 15)
);

create table if not exists public.loyalty_transactions (
  id bigint generated by default as identity primary key,
  phone_digits text not null references public.loyalty_accounts(phone_digits) on update cascade on delete restrict,
  order_number text,
  transaction_type text not null check (transaction_type in ('earn','redeem','adjustment')),
  points_delta integer not null check (points_delta <> 0),
  description text not null default '',
  created_by uuid,
  created_at timestamptz not null default now()
);

create index if not exists loyalty_transactions_phone_created_idx
  on public.loyalty_transactions(phone_digits, created_at desc);
create unique index if not exists loyalty_transactions_one_earn_per_order
  on public.loyalty_transactions(order_number)
  where transaction_type = 'earn' and order_number is not null;

alter table public.loyalty_accounts enable row level security;
alter table public.loyalty_transactions enable row level security;
revoke all on table public.loyalty_accounts from anon, authenticated;
revoke all on table public.loyalty_transactions from anon, authenticated;

create or replace function public.award_loyalty_points_on_delivery()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_phone text;
  v_points integer;
  v_transaction_id bigint;
begin
  if new.status is distinct from 'Teslim edildi'
     or old.status is not distinct from new.status then
    return new;
  end if;

  v_phone := regexp_replace(coalesce(new.customer_phone, ''), '[^0-9]', '', 'g');
  v_points := floor(greatest(coalesce(new.total, 0), 0) / 10)::integer;

  if length(v_phone) not between 10 and 15 or v_points < 1
     or nullif(trim(coalesce(new.order_number, '')), '') is null then
    return new;
  end if;

  insert into public.loyalty_accounts (phone_digits, customer_name)
  values (v_phone, left(coalesce(new.customer_name, ''), 120))
  on conflict (phone_digits) do update
    set customer_name = case
      when excluded.customer_name <> '' then excluded.customer_name
      else public.loyalty_accounts.customer_name
    end,
    updated_at = now();

  insert into public.loyalty_transactions
    (phone_digits, order_number, transaction_type, points_delta, description)
  values
    (v_phone, trim(new.order_number), 'earn', v_points,
     'Teslim edilen sipariş için otomatik puan')
  on conflict do nothing
  returning id into v_transaction_id;

  if v_transaction_id is not null then
    update public.loyalty_accounts
       set points_balance = points_balance + v_points,
           lifetime_earned = lifetime_earned + v_points,
           updated_at = now()
     where phone_digits = v_phone;
  end if;

  return new;
exception when others then
  raise warning 'YEMEK TADINDA loyalty award failed for order %: %', new.order_number, sqlerrm;
  return new;
end;
$function$;

revoke all on function public.award_loyalty_points_on_delivery() from public, anon, authenticated;

drop trigger if exists trg_award_loyalty_points_on_delivery on public.orders;
create trigger trg_award_loyalty_points_on_delivery
after update of status on public.orders
for each row
when (new.status = 'Teslim edildi' and old.status is distinct from new.status)
execute function public.award_loyalty_points_on_delivery();

create or replace function public.get_customer_loyalty_summary(p_phone text, p_order_number text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_phone text := regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
  v_order text := upper(trim(coalesce(p_order_number, '')));
  v_account public.loyalty_accounts%rowtype;
  v_recent jsonb;
begin
  if length(v_phone) not between 10 and 15 or length(v_order) < 5 then
    raise exception 'Sipariş ve telefon bilgileri doğrulanamadı.';
  end if;

  if not exists (
    select 1 from public.orders o
     where upper(trim(coalesce(o.order_number, ''))) = v_order
       and regexp_replace(coalesce(o.customer_phone, ''), '[^0-9]', '', 'g') = v_phone
  ) then
    raise exception 'Sipariş ve telefon bilgileri eşleşmiyor.';
  end if;

  select a.* into v_account
    from public.loyalty_accounts a
   where a.phone_digits = v_phone;

  select coalesce(
    jsonb_agg(jsonb_build_object(
      'transaction_type', t.transaction_type,
      'points_delta', t.points_delta,
      'description', t.description,
      'order_number', t.order_number,
      'created_at', t.created_at
    ) order by t.created_at desc),
    '[]'::jsonb
  ) into v_recent
    from (
      select lt.* from public.loyalty_transactions lt
       where lt.phone_digits = v_phone
       order by lt.created_at desc limit 20
    ) t;

  return jsonb_build_object(
    'points_balance', coalesce(v_account.points_balance, 0),
    'lifetime_earned', coalesce(v_account.lifetime_earned, 0),
    'lifetime_redeemed', coalesce(v_account.lifetime_redeemed, 0),
    'recent_transactions', v_recent,
    'points_per_tl', 0.1,
    'redemption_points', 100,
    'redemption_value_tl', 10
  );
end;
$function$;

revoke all on function public.get_customer_loyalty_summary(text, text) from public;
grant execute on function public.get_customer_loyalty_summary(text, text) to anon, authenticated;

create or replace function public.admin_list_loyalty_accounts()
returns table (
  phone_digits text,
  customer_name text,
  points_balance integer,
  lifetime_earned integer,
  lifetime_redeemed integer,
  updated_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $function$
begin
  if not public.is_admin() then
    raise exception 'Yönetici yetkisi gerekli.';
  end if;

  return query
    select a.phone_digits, a.customer_name, a.points_balance,
           a.lifetime_earned, a.lifetime_redeemed, a.updated_at
      from public.loyalty_accounts a
     order by a.points_balance desc, a.updated_at desc;
end;
$function$;

revoke all on function public.admin_list_loyalty_accounts() from public, anon;
grant execute on function public.admin_list_loyalty_accounts() to authenticated;

create or replace function public.admin_adjust_loyalty_points(
  p_phone text, p_customer_name text, p_points_delta integer, p_description text
)
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_phone text := regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g');
  v_balance integer;
  v_description text := left(trim(coalesce(p_description, '')), 240);
begin
  if not public.is_admin() then
    raise exception 'Yönetici yetkisi gerekli.';
  end if;
  if length(v_phone) not between 10 and 15 then
    raise exception 'Geçerli müşteri telefon numarası girin.';
  end if;
  if p_points_delta is null or p_points_delta = 0 or abs(p_points_delta::bigint) > 100000 then
    raise exception 'Puan değişikliği 1 ile 100000 arasında olmalıdır.';
  end if;
  if v_description = '' then
    raise exception 'İşlem açıklaması zorunludur.';
  end if;

  insert into public.loyalty_accounts (phone_digits, customer_name)
  values (v_phone, left(coalesce(p_customer_name, ''), 120))
  on conflict (phone_digits) do update
    set customer_name = case
      when left(coalesce(p_customer_name, ''), 120) <> ''
        then left(coalesce(p_customer_name, ''), 120)
      else public.loyalty_accounts.customer_name
    end,
    updated_at = now();

  select a.points_balance into v_balance
    from public.loyalty_accounts a
   where a.phone_digits = v_phone
   for update;

  if v_balance + p_points_delta < 0 then
    raise exception 'Müşterinin mevcut puanı bu işlem için yetersiz.';
  end if;

  update public.loyalty_accounts
     set points_balance = points_balance + p_points_delta,
         lifetime_earned = lifetime_earned + greatest(p_points_delta, 0),
         lifetime_redeemed = lifetime_redeemed + greatest(-p_points_delta, 0),
         updated_at = now()
   where phone_digits = v_phone
   returning points_balance into v_balance;

  insert into public.loyalty_transactions
    (phone_digits, transaction_type, points_delta, description, created_by)
  values
    (v_phone, case when p_points_delta < 0 then 'redeem' else 'adjustment' end,
     p_points_delta, v_description, auth.uid());

  return v_balance;
end;
$function$;

revoke all on function public.admin_adjust_loyalty_points(text, text, integer, text) from public, anon;
grant execute on function public.admin_adjust_loyalty_points(text, text, integer, text) to authenticated;
