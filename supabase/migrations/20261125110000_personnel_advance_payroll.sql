$function$;

create or replace function public.admin_save_personnel_month(
  p_personnel_id bigint, p_month date, p_days jsonb, p_signatory_name text
) returns jsonb language plpgsql security definer set search_path = ''
as $function$
declare
  v_start_date date; v_item jsonb; v_day integer; v_code text; v_days_in_month integer;
  v_work integer := 0; v_leave integer := 0; v_annual integer := 0; v_absent integer := 0;
begin
  if not coalesce(public.is_admin(), false) then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  if p_month is null or p_month <> date_trunc('month', p_month)::date then
    raise exception 'Ay tarihi ayın ilk günü olmalıdır.';
  end if;
  if jsonb_typeof(coalesce(p_days, '[]'::jsonb)) <> 'array' then
    raise exception 'Gün kayıtları liste biçiminde olmalıdır.';
  end if;
  if char_length(coalesce(p_signatory_name, '')) > 180 then
    raise exception 'Puantajı hazırlayan adı çok uzun.';
  end if;
  select start_date into v_start_date from public.personnel where id = p_personnel_id;
  if v_start_date is null then raise exception 'Personel kaydı bulunamadı.'; end if;
  v_days_in_month := extract(day from (p_month + interval '1 month - 1 day'))::integer;
  for v_item in select value from jsonb_array_elements(coalesce(p_days, '[]'::jsonb)) loop
    v_day := (v_item->>'day')::integer;
    v_code := upper(btrim(coalesce(v_item->>'code', '')));
    if v_day < 1 or v_day > v_days_in_month then
      raise exception 'Ay içinde bulunmayan bir gün gönderildi: %', v_day;
    end if;
    if v_code not in ('X', 'I', 'Y', 'D') then raise exception 'Geçersiz puantaj işareti: %', v_code; end if;
    if (p_month + (v_day - 1)) < v_start_date then
      raise exception 'İşe başlama tarihinden önceki güne puantaj girilemez.';
    end if;
  end loop;
  insert into public.personnel_months(personnel_id, month_date, signatory_name, updated_at)
  values(p_personnel_id, p_month, btrim(coalesce(p_signatory_name, '')), now())
  on conflict(personnel_id, month_date) do update
    set signatory_name = excluded.signatory_name, updated_at = now();
  delete from public.personnel_attendance
  where personnel_id = p_personnel_id and attendance_date >= p_month
    and attendance_date < (p_month + interval '1 month');
  for v_item in select value from jsonb_array_elements(coalesce(p_days, '[]'::jsonb)) loop
    v_day := (v_item->>'day')::integer;
    v_code := upper(btrim(coalesce(v_item->>'code', '')));
    insert into public.personnel_attendance(personnel_id, attendance_date, day_code)
    values(p_personnel_id, p_month + (v_day - 1), v_code);
    if v_code = 'X' then v_work := v_work + 1;
    elsif v_code = 'I' then v_leave := v_leave + 1;
    elsif v_code = 'Y' then v_annual := v_annual + 1;
    elsif v_code = 'D' then v_absent := v_absent + 1;
    end if;
  end loop;
  return jsonb_build_object('success', true, 'work_days', v_work,
    'leave_days', v_leave, 'annual_leave_days', v_annual,
    'absent_days', v_absent, 'total_leave_days', v_leave + v_annual);
end;
$function$;

create or replace function public.admin_get_personnel_year_summary(p_personnel_id bigint, p_year integer)
returns jsonb language plpgsql security definer set search_path = ''
as $function$
declare v_result jsonb;
begin
  if not coalesce(public.is_admin(), false) then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  if p_year < 2000 or p_year > 2200 then raise exception 'Geçerli bir yıl girin.'; end if;
  if not exists(select 1 from public.personnel where id = p_personnel_id) then
    raise exception 'Personel kaydı bulunamadı.';
  end if;
  select jsonb_agg(jsonb_build_object(
    'month', g.month_no,
    'work_days', coalesce(a.work_days, 0),
    'leave_days', coalesce(a.leave_days, 0),
    'annual_leave_days', coalesce(a.annual_leave_days, 0),
    'absent_days', coalesce(a.absent_days, 0),
    'signatory_name', coalesce(pm.signatory_name, '')
  ) order by g.month_no)
  into v_result
  from generate_series(1, 12) as g(month_no)
  left join public.personnel_months pm
    on pm.personnel_id = p_personnel_id and pm.month_date = make_date(p_year, g.month_no, 1)
  left join lateral (
    select
      count(*) filter(where day_code = 'X')::integer as work_days,
      count(*) filter(where day_code = 'I')::integer as leave_days,
      count(*) filter(where day_code = 'Y')::integer as annual_leave_days,
      count(*) filter(where day_code = 'D')::integer as absent_days
    from public.personnel_attendance a0
    where a0.personnel_id = p_personnel_id
      and a0.attendance_date >= make_date(p_year, g.month_no, 1)
      and a0.attendance_date < (make_date(p_year, g.month_no, 1) + interval '1 month')
  ) a on true;
  return coalesce(v_result, '[]'::jsonb);
end;
$function$;

