create or replace function public.admin_list_personnel()
returns table(id bigint,full_name text,start_date date,job_title text,national_id_masked text,phone text,is_active boolean,created_at timestamptz)
language plpgsql security definer set search_path=''
as $$
declare v_key text;
begin
 if not coalesce(public.is_admin(),false) then raise exception 'Yönetici yetkisi gerekli.' using errcode='42501'; end if;
 select decrypted_secret into v_key from vault.decrypted_secrets where name='yemektadinda_personnel_tc_key' limit 1;
 if v_key is null then raise exception 'Kimlik şifreleme anahtarı bulunamadı.'; end if;
 return query
 select p.id,p.full_name,p.start_date,p.job_title,
  left(extensions.pgp_sym_decrypt(decode(p.national_id_cipher,'hex'),v_key),2)||'*******'||
  right(extensions.pgp_sym_decrypt(decode(p.national_id_cipher,'hex'),v_key),2),
  p.phone,p.is_active,p.created_at
 from public.personnel p order by p.is_active desc,p.full_name,p.id;
end $$;

create or replace function public.admin_get_personnel(p_personnel_id bigint)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_key text; v_result jsonb;
begin
 if not coalesce(public.is_admin(),false) then raise exception 'Yönetici yetkisi gerekli.' using errcode='42501'; end if;
 select decrypted_secret into v_key from vault.decrypted_secrets where name='yemektadinda_personnel_tc_key' limit 1;
 if v_key is null then raise exception 'Kimlik şifreleme anahtarı bulunamadı.'; end if;
 select jsonb_build_object('id',p.id,'full_name',p.full_name,'start_date',p.start_date,'job_title',p.job_title,
  'national_id',extensions.pgp_sym_decrypt(decode(p.national_id_cipher,'hex'),v_key),'phone',p.phone,
  'is_active',p.is_active,'created_at',p.created_at)
 into v_result from public.personnel p where p.id=p_personnel_id;
 if v_result is null then raise exception 'Personel kaydı bulunamadı.'; end if;
 return v_result;
end $$;

create or replace function public.admin_save_personnel(
 p_personnel_id bigint,p_full_name text,p_start_date date,p_job_title text,p_national_id text,p_phone text,p_is_active boolean
)
returns bigint language plpgsql security definer set search_path=''
as $$
declare
 v_key text; v_id bigint; v_tc text:=regexp_replace(coalesce(p_national_id,''),'[^0-9]','','g');
 v_cipher text; v_hash text; v_digits integer[]; v_odd integer:=0; v_even integer:=0; v_i integer;
begin
 if not coalesce(public.is_admin(),false) then raise exception 'Yönetici yetkisi gerekli.' using errcode='42501'; end if;
 if p_full_name is null or char_length(btrim(p_full_name)) not between 2 and 150 then raise exception 'Ad soyad 2-150 karakter arasında olmalı.'; end if;
 if p_start_date is null then raise exception 'İşe başlama tarihi zorunludur.'; end if;
 if p_job_title is null or char_length(btrim(p_job_title)) not between 2 and 120 then raise exception 'Görev 2-120 karakter arasında olmalı.'; end if;
 if char_length(coalesce(p_phone,''))>30 then raise exception 'Telefon alanı çok uzun.'; end if;
 select decrypted_secret into v_key from vault.decrypted_secrets where name='yemektadinda_personnel_tc_key' limit 1;
 if v_key is null then raise exception 'Kimlik şifreleme anahtarı bulunamadı.'; end if;
 if v_tc<>'' then
  if v_tc !~ '^[0-9]{11}$' or left(v_tc,1)='0' then raise exception 'TC Kimlik No 11 haneli olmalı ve 0 ile başlamamalıdır.'; end if;
  v_digits:=array(select substring(v_tc from pos for 1)::integer from generate_series(1,11) pos);
  for v_i in 1..9 loop
   if v_i%2=1 then v_odd:=v_odd+v_digits[v_i]; else v_even:=v_even+v_digits[v_i]; end if;
  end loop;
  if ((v_odd*7-v_even)%10+10)%10<>v_digits[10] or (select sum(v_digits[pos]) from generate_series(1,10) pos)%10<>v_digits[11] then
   raise exception 'TC Kimlik No doğrulama kontrolü başarısız.';
  end if;
  v_cipher:=encode(extensions.pgp_sym_encrypt(v_tc,v_key,'cipher-algo=aes256'),'hex');
  v_hash:=encode(extensions.hmac(v_tc,v_key,'sha256'),'hex');
 elsif p_personnel_id is null then raise exception 'Yeni personel için TC Kimlik No zorunludur.';
 end if;
 if p_personnel_id is null then
  insert into public.personnel(full_name,start_date,job_title,national_id_cipher,national_id_hash,phone,is_active,created_by)
  values(btrim(p_full_name),p_start_date,btrim(p_job_title),v_cipher,v_hash,btrim(coalesce(p_phone,'')),coalesce(p_is_active,true),auth.uid())
  returning id into v_id;
 else
  update public.personnel set full_name=btrim(p_full_name),start_date=p_start_date,job_title=btrim(p_job_title),
   national_id_cipher=coalesce(v_cipher,national_id_cipher),national_id_hash=coalesce(v_hash,national_id_hash),
   phone=btrim(coalesce(p_phone,'')),is_active=coalesce(p_is_active,true),updated_at=now()
  where id=p_personnel_id returning id into v_id;
  if v_id is null then raise exception 'Personel kaydı bulunamadı.'; end if;
 end if;
 return v_id;
exception when unique_violation then raise exception 'Bu TC Kimlik No ile kayıtlı başka personel var.';
end $$;

create or replace function public.admin_set_personnel_active(p_personnel_id bigint,p_is_active boolean)
returns boolean language plpgsql security definer set search_path=''
as $$
begin
 if not coalesce(public.is_admin(),false) then raise exception 'Yönetici yetkisi gerekli.' using errcode='42501'; end if;
 update public.personnel set is_active=coalesce(p_is_active,false),updated_at=now() where id=p_personnel_id;
 if not found then raise exception 'Personel kaydı bulunamadı.'; end if;
 return true;
end $$;

create or replace function public.admin_get_personnel_month(p_personnel_id bigint,p_month date)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_result jsonb;
begin
 if not coalesce(public.is_admin(),false) then raise exception 'Yönetici yetkisi gerekli.' using errcode='42501'; end if;
 if p_month is null or p_month<>date_trunc('month',p_month)::date then raise exception 'Ay tarihi ayın ilk günü olmalıdır.'; end if;
 if not exists(select 1 from public.personnel where id=p_personnel_id) then raise exception 'Personel kaydı bulunamadı.'; end if;
 select jsonb_build_object('personnel_id',p_personnel_id,'month_date',p_month,
  'signatory_name',coalesce(pm.signatory_name,''),
  'days',coalesce((select jsonb_agg(jsonb_build_object('day',extract(day from a.attendance_date)::integer,'code',a.day_code) order by a.attendance_date)
   from public.personnel_attendance a where a.personnel_id=p_personnel_id
    and a.attendance_date>=p_month and a.attendance_date<(p_month+interval '1 month')),'[]'::jsonb))
 into v_result from (select 1) seed
 left join public.personnel_months pm on pm.personnel_id=p_personnel_id and pm.month_date=p_month;
 return coalesce(v_result,'{}'::jsonb);
end $$;

create or replace function public.admin_save_personnel_month(p_personnel_id bigint,p_month date,p_days jsonb,p_signatory_name text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_start_date date; v_item jsonb; v_day integer; v_code text; v_days_in_month integer;
 v_work integer:=0; v_leave integer:=0; v_annual integer:=0;
begin
 if not coalesce(public.is_admin(),false) then raise exception 'Yönetici yetkisi gerekli.' using errcode='42501'; end if;
 if p_month is null or p_month<>date_trunc('month',p_month)::date then raise exception 'Ay tarihi ayın ilk günü olmalıdır.'; end if;
 if jsonb_typeof(coalesce(p_days,'[]'::jsonb))<>'array' then raise exception 'Gün kayıtları liste biçiminde olmalıdır.'; end if;
 if char_length(coalesce(p_signatory_name,''))>180 then raise exception 'Puantajı hazırlayan adı çok uzun.'; end if;
 select start_date into v_start_date from public.personnel where id=p_personnel_id;
 if v_start_date is null then raise exception 'Personel kaydı bulunamadı.'; end if;
 v_days_in_month:=extract(day from (p_month+interval '1 month - 1 day'))::integer;
 for v_item in select value from jsonb_array_elements(coalesce(p_days,'[]'::jsonb)) loop
  v_day:=(v_item->>'day')::integer; v_code:=upper(btrim(coalesce(v_item->>'code','')));
  if v_day<1 or v_day>v_days_in_month then raise exception 'Ay içinde bulunmayan bir gün gönderildi: %',v_day; end if;
  if v_code not in ('X','I','Y') then raise exception 'Geçersiz puantaj işareti: %',v_code; end if;
  if (p_month+(v_day-1))<v_start_date then raise exception 'İşe başlama tarihinden önceki güne puantaj girilemez.'; end if;
 end loop;
 insert into public.personnel_months(personnel_id,month_date,signatory_name,updated_at)
 values(p_personnel_id,p_month,btrim(coalesce(p_signatory_name,'')),now())
 on conflict(personnel_id,month_date) do update set signatory_name=excluded.signatory_name,updated_at=now();
 delete from public.personnel_attendance where personnel_id=p_personnel_id and attendance_date>=p_month and attendance_date<(p_month+interval '1 month');
 for v_item in select value from jsonb_array_elements(coalesce(p_days,'[]'::jsonb)) loop
  v_day:=(v_item->>'day')::integer; v_code:=upper(btrim(coalesce(v_item->>'code','')));
  insert into public.personnel_attendance(personnel_id,attendance_date,day_code) values(p_personnel_id,p_month+(v_day-1),v_code);
  if v_code='X' then v_work:=v_work+1; elsif v_code='I' then v_leave:=v_leave+1; elsif v_code='Y' then v_annual:=v_annual+1; end if;
 end loop;
 return jsonb_build_object('success',true,'work_days',v_work,'leave_days',v_leave,'annual_leave_days',v_annual,'total_leave_days',v_leave+v_annual);
end $$;

create or replace function public.admin_get_personnel_year_summary(p_personnel_id bigint,p_year integer)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_result jsonb;
begin
 if not coalesce(public.is_admin(),false) then raise exception 'Yönetici yetkisi gerekli.' using errcode='42501'; end if;
 if p_year<2000 or p_year>2200 then raise exception 'Geçerli bir yıl girin.'; end if;
 if not exists(select 1 from public.personnel where id=p_personnel_id) then raise exception 'Personel kaydı bulunamadı.'; end if;
 select jsonb_agg(jsonb_build_object('month',g.month_no,'work_days',coalesce(a.work_days,0),
  'leave_days',coalesce(a.leave_days,0),'annual_leave_days',coalesce(a.annual_leave_days,0),
  'signatory_name',coalesce(pm.signatory_name,'')) order by g.month_no)
 into v_result from generate_series(1,12) as g(month_no)
 left join public.personnel_months pm on pm.personnel_id=p_personnel_id and pm.month_date=make_date(p_year,g.month_no,1)
 left join lateral (
  select count(*) filter(where day_code='X')::integer as work_days,
   count(*) filter(where day_code='I')::integer as leave_days,
   count(*) filter(where day_code='Y')::integer as annual_leave_days
  from public.personnel_attendance a0 where a0.personnel_id=p_personnel_id
   and a0.attendance_date>=make_date(p_year,g.month_no,1)
   and a0.attendance_date<(make_date(p_year,g.month_no,1)+interval '1 month')
 ) a on true;
 return coalesce(v_result,'[]'::jsonb);
end $$;

